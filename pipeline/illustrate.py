"""AI illustrations for abstract beats, generated with SDXL on Kaggle's free GPU.

The rule that keeps the channel honest: AI only draws *ideas*, never the real world.

  eligible:  B-roll beats with no names in them ("gears grinding to a halt",
             "two paths diverging", "microscopic view of glass")
  never:     people, products, companies, brands, places on a map, documents, figures.
             A beat whose search words contain a proper noun ("Foxconn factory",
             "iPhone Duo screen") is a real-world thing and stays photo-or-card only.

Everything is drawn in one house style (ink + duotone), so it reads as deliberate illustration,
never as a photo of something that didn't happen. Results land in the Pictures tab as options
labeled "AI illustration"; nothing is used unless you pick it.

Flow: the dashboard queues beats -> the GitHub worker writes a Kaggle script with the prompts
baked in -> pushes it as a private GPU notebook -> waits -> downloads the images -> stores them
with the episode as candidates.
"""
from __future__ import annotations

import base64
import json
import os
import re
import tempfile
import time
from pathlib import Path

from .config import env, load_config
from .episode import Episode

KAGGLE_TIMEOUT = 50 * 60  # seconds to wait for the notebook, queue time included


class IllustrateError(RuntimeError):
    pass


def cfg() -> dict:
    return load_config()["illustrate"]


# ──────────────────────────── the rule ────────────────────────────

_PROPER = re.compile(r"\b\w*[A-Z]\w*")


def eligible(beat_type: str, query: str) -> tuple[bool, str]:
    """(allowed, reason). Conservative on purpose: when in doubt, it's a real-world thing."""
    if beat_type != "broll":
        return False, "Only B-roll beats can be illustrated. People, products, documents and figures stay real."
    words = query.strip()
    # Any capital letter anywhere = a name, brand or product ("Foxconn", "iPhone", "Apple").
    # Scripts write generic shots in lowercase, so this errs on the side of "real thing".
    if _PROPER.search(words):
        return False, "This beat names a real person, product or company, so it needs a real picture."
    if re.search(r"\b(19|20)\d{2}\b", words):
        return False, "This beat is about a specific dated event, so it needs a real picture."
    return True, ""


def prompt_for(query: str) -> str:
    subject = re.sub(r"\b(stock footage|footage|b-roll|slow motion|fast motion|close up of|animation of|animated)\b",
                     "", query, flags=re.I)
    subject = re.sub(r"\s+", " ", subject).strip(" ,.-")
    return f"{subject}, {cfg()['style'].strip()}"


# ──────────────────────────── queueing (dashboard side) ────────────────────────────

def candidates_for(manifest: dict) -> list[str]:
    """Beat ids that may be illustrated and don't have AI options yet."""
    out = []
    for b in manifest.get("beats", []):
        ok, _ = eligible(b["type"], b["query"])
        if ok and not any(c["source"] == "ai" for c in b["candidates"]):
            out.append(b["id"])
    return out


# ──────────────────────────── the Kaggle notebook ────────────────────────────

KERNEL_TEMPLATE = r'''
# Generated by docu-pipeline. Draws illustrations for abstract beats with SDXL.
import json, os, subprocess, sys, time, traceback

JOB = json.loads(r"""__JOB__""")
OUT = "/kaggle/working"
started = time.time()
made = {}


def save(error=None):
    # Written after every beat, so a crash halfway still hands back what was drawn.
    json.dump({"made": made, "seconds": round(time.time() - started), "error": error},
              open(os.path.join(OUT, "result.json"), "w"))


try:
    import torch
    # Check the GPU before downloading 6 GB of model: no GPU, or one this torch can't drive (P100).
    if not torch.cuda.is_available():
        raise RuntimeError("No GPU on this session. Kaggle GPU needs a phone-verified account and weekly quota left.")
    name = torch.cuda.get_device_name(0)
    print(f"GPU: {name}, torch {torch.__version__}", flush=True)
    torch.zeros(1, device="cuda").add_(1)  # fails fast with "no kernel image" on unsupported cards

    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "diffusers>=0.27", "accelerate"], check=False)
    from diffusers import AutoencoderKL, StableDiffusionXLPipeline

    vae = AutoencoderKL.from_pretrained(JOB["vae"], torch_dtype=torch.float16)
    pipe = StableDiffusionXLPipeline.from_pretrained(
        JOB["model"], vae=vae, torch_dtype=torch.float16, variant="fp16", use_safetensors=True
    ).to("cuda")
    pipe.set_progress_bar_config(disable=True)
    print(f"model loaded ({time.time() - started:.0f}s)", flush=True)

    for item in JOB["items"]:
        made[item["id"]] = []
        for k in range(JOB["per_beat"]):
            g = torch.Generator("cuda").manual_seed(item["seed"] + k)
            img = pipe(item["prompt"], negative_prompt=JOB["negative"], width=JOB["width"], height=JOB["height"],
                       num_inference_steps=JOB["steps"], guidance_scale=JOB["guidance"], generator=g).images[0]
            fname = f"{item['id']}-{k}.jpg"
            img.save(os.path.join(OUT, fname), quality=88)
            made[item["id"]].append(fname)
        save()
        print(f"{item['id']}: done ({time.time() - started:.0f}s)", flush=True)
    save()
except Exception as e:
    traceback.print_exc()
    save(f"{e.__class__.__name__}: {e}"[:400])
    # Exit cleanly: the error travels back in result.json together with anything already drawn.
'''


def build_kernel(folder: Path, items: list[dict], username: str) -> str:
    c = cfg()
    job = {"model": c["model"], "vae": c["vae"], "per_beat": c["per_beat"], "steps": c["steps"],
           "guidance": c["guidance"], "width": c["width"], "height": c["height"],
           "negative": c["negative"].strip(), "items": items}
    code = KERNEL_TEMPLATE.replace("__JOB__", json.dumps(job).replace('"""', r'\"\"\"'))
    (folder / "illustrate.py").write_text(code, encoding="utf-8")
    kernel_id = f"{username}/{c['kernel_slug']}"
    (folder / "kernel-metadata.json").write_text(json.dumps({
        "id": kernel_id, "title": c["kernel_slug"], "code_file": "illustrate.py",
        "language": "python", "kernel_type": "script", "is_private": True,
        "enable_gpu": True, "enable_internet": True, "machine_shape": c.get("accelerator", "NvidiaTeslaT4"),
        "dataset_sources": [], "competition_sources": [], "kernel_sources": [], "model_sources": [],
    }, indent=2), encoding="utf-8")
    return kernel_id


def run_on_kaggle(items: list[dict], out_dir: Path) -> dict:
    """Push the notebook, wait for it, download the images. Returns {beat_id: [image paths]}."""
    if os.getenv("DOCU_MOCK_ILLUSTRATE") == "1":
        return _demo_images(items, out_dir)
    username = env("KAGGLE_USERNAME")
    if not (username and env("KAGGLE_API_TOKEN")):
        raise IllustrateError("Kaggle isn't connected. Add KAGGLE_USERNAME and KAGGLE_API_TOKEN as "
                              "GitHub repository secrets (Settings → Secrets and variables → Actions).")
    from kaggle.api.kaggle_api_extended import KaggleApi  # installed on the worker only

    api = KaggleApi()
    api.authenticate()
    with tempfile.TemporaryDirectory() as tmp:
        kernel_id = build_kernel(Path(tmp), items, username)
        print(f"  pushing {kernel_id} with {len(items)} beats on {cfg().get('accelerator', 'NvidiaTeslaT4')}")
        try:
            api.kernels_push(tmp)
        except Exception as e:  # an accelerator name Kaggle doesn't know: fall back to plain "any GPU"
            print(f"  push with accelerator failed ({e}); retrying with the default GPU")
            meta_file = Path(tmp) / "kernel-metadata.json"
            meta = json.loads(meta_file.read_text())
            meta.pop("machine_shape", None)
            meta_file.write_text(json.dumps(meta))
            api.kernels_push(tmp)

    deadline = time.time() + KAGGLE_TIMEOUT
    status = failure = ""
    while time.time() < deadline:
        time.sleep(30)
        resp = api.kernels_status(kernel_id)
        status = str(getattr(resp, "status", resp)).lower()
        print(f"  kaggle: {status}")
        if "complete" in status:
            break
        if "error" in status or "cancel" in status:
            failure = getattr(resp, "failure_message", "") or ""
            break
    else:
        raise IllustrateError("Kaggle took longer than 50 minutes (GPU queue busy?). Try again later.")

    try:
        api.kernels_output(kernel_id, str(out_dir))
    except Exception as e:
        print(f"  couldn't download notebook output: {e}")
    result_file = out_dir / "result.json"
    result = json.loads(result_file.read_text()) if result_file.exists() else {}
    made = {beat_id: [out_dir / name for name in names if (out_dir / name).exists()]
            for beat_id, names in (result.get("made") or {}).items()}
    made = {k: v for k, v in made.items() if v}

    reason = result.get("error") or failure or (f"status {status}" if "complete" not in status else "")
    if not reason and not made:
        reason = "it finished but returned no images"
    if reason and not made:
        tail = _log_tail(out_dir)
        print("  ---- kaggle log (tail) ----\n" + tail)
        raise IllustrateError(f"The Kaggle notebook failed: {reason}"
                              + (f" | log: {tail[-300:]}" if tail and not result.get("error") else "")
                              + f" — full log at kaggle.com/code/{kernel_id}")
    if reason:
        print(f"  partial result, notebook stopped early: {reason}")
    return made


def _log_tail(out_dir: Path, lines: int = 25) -> str:
    """Kaggle's log is a JSON list of {stream_name, data}; flatten it and keep the end."""
    logs = list(out_dir.glob("*.log"))
    if not logs:
        return ""
    raw = logs[0].read_text(errors="replace")
    try:
        text = "".join(chunk.get("data", "") for chunk in json.loads(raw))
    except (ValueError, AttributeError):
        text = raw
    return "\n".join(text.strip().splitlines()[-lines:])


def _demo_images(items: list[dict], out_dir: Path) -> dict:
    """Demo/tests: stand-in images instead of a Kaggle run."""
    import shutil
    from .config import ROOT
    samples = sorted((ROOT / "web" / "demo").glob("sample*.jpg"))
    out = {}
    for n, item in enumerate(items):
        out[item["id"]] = []
        for k in range(cfg()["per_beat"]):
            dest = out_dir / f"{item['id']}-{k}.jpg"
            shutil.copy(samples[(n + k) % len(samples)], dest)
            out[item["id"]].append(dest)
    return out


# ──────────────────────────── storing results ────────────────────────────

def store(slug: str, images: dict[str, list[Path]]) -> int:
    """Add the images to each beat as 'AI illustration' options. Doesn't change your picks."""
    ep = Episode.load(slug)
    m = ep.read("visuals.json")
    added = 0
    for b in m.get("beats", []):
        for k, path in enumerate(images.get(b["id"], [])):
            file = f"visuals/ai/{b['id']}-{k}.b64"
            ep.write(file, "image/jpeg;" + base64.b64encode(path.read_bytes()).decode())
            b["candidates"] = [c for c in b["candidates"] if c.get("file") != file]
            # after real picks and uploads, before the fallback card
            card_at = next((i for i, c in enumerate(b["candidates"]) if c["source"] == "card"), len(b["candidates"]))
            b["candidates"].insert(card_at, {
                "source": "ai", "kind": "image", "file": file,
                "title": "AI illustration", "credit": "AI illustration (SDXL)",
                "license": "CreativeML OpenRAIL++-M", "prompt": prompt_for(b["query"]),
            })
            if b["chosen"] >= card_at:
                b["chosen"] += 1  # keep pointing at the same option you had picked
            added += 1
    ep.write("visuals.json", m)
    return added


def run(slug: str, beat_ids: list[str]) -> dict:
    ep = Episode.load(slug)
    m = ep.read("visuals.json") or {}
    beats = {b["id"]: b for b in m.get("beats", [])}
    items = []
    for i, bid in enumerate(beat_ids):
        b = beats.get(bid)
        if not b:
            continue
        ok, _ = eligible(b["type"], b["query"])
        if ok:  # re-checked here: the queue can't be used to slip a real-world beat through
            items.append({"id": bid, "prompt": prompt_for(b["query"]), "seed": 1000 + i * 17})
    if not items:
        raise IllustrateError("None of those beats can be illustrated.")
    started = time.time()
    print(f"[illustrate] {ep.read('meta.json')['topic']}: {len(items)} beats")
    with tempfile.TemporaryDirectory() as tmp:
        images = run_on_kaggle(items, Path(tmp))
        added = store(slug, images)
    meta = ep.read("meta.json")
    meta["illustrate"] = {**(meta.get("illustrate") or {}), "state": "done", "added": added,
                          "seconds_taken": round(time.time() - started)}
    ep.write("meta.json", meta)
    print(f"  ✓ {added} illustrations added ({time.time() - started:.0f}s)")
    return meta["illustrate"]
