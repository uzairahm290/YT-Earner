"""AI illustrations for abstract beats, generated with SDXL on Kaggle's free GPU.

The rule that keeps the channel honest: AI only draws *ideas*, never the real world.

  eligible:  B-roll beats with no names in them ("gears grinding to a halt",
             "two paths diverging", "microscopic view of glass")
  never:     people, products, companies, brands, places on a map, documents, figures.
             A beat whose search words contain a proper noun ("Foxconn factory",
             "iPhone Duo screen") is a real-world thing and stays photo-or-card only.

Everything is drawn in one house style (ink + duotone), so it reads as deliberate illustration,
never as a photo of something that didn't happen. Results land in the Pictures tab as options
labeled "AI illustration"; nothing is used unless you pick it.

Flow: the dashboard queues beats -> the GitHub worker writes a Kaggle script with the prompts
baked in -> pushes it as a private GPU notebook -> waits -> downloads the images -> stores them
with the episode as candidates.
"""
from __future__ import annotations

import base64
import json
import os
import re
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path

from .config import env, load_config
from .episode import Episode

KAGGLE_TIMEOUT = 40 * 60  # wait this long in one worker run; after that a later run collects


class IllustrateError(RuntimeError):
    pass


def cfg() -> dict:
    return load_config()["illustrate"]


# ──────────────────────────── the rule ────────────────────────────

_PROPER = re.compile(r"\b\w*[A-Z]\w*")


def eligible(beat_type: str, query: str) -> tuple[bool, str]:
    """(allowed, reason). Conservative on purpose: when in doubt, it's a real-world thing."""
    if beat_type != "broll":
        return False, "Only B-roll beats can be illustrated. People, products, documents and figures stay real."
    words = query.strip()
    # Any capital letter anywhere = a name, brand or product ("Foxconn", "iPhone", "Apple").
    # Scripts write generic shots in lowercase, so this errs on the side of "real thing".
    if _PROPER.search(words):
        return False, "This beat names a real person, product or company, so it needs a real picture."
    if re.search(r"\b(19|20)\d{2}\b", words):
        return False, "This beat is about a specific dated event, so it needs a real picture."
    return True, ""


def check_prompt(text: str) -> tuple[bool, str]:
    """A prompt you typed yourself, for any beat: still no names, brands or dates."""
    if len(text.strip()) < 4:
        return False, "Describe the idea in a few words."
    if _PROPER.search(text) or re.search(r"\b(19|20)\d{2}\b", text):
        return False, ("Leave out names, brands and years: describe the idea instead "
                       "(\"a phone splitting in two\", not \"iPhone Duo\"). AI never draws real people or products.")
    return True, ""


_PEOPLE = re.compile(r"\b(man|men|woman|women|person|people|crowd|face|faces|portrait|ceo|founder|founders|"
                     r"worker|workers|engineer|engineers|employee|employees|staff|boy|girl|child|children|kid|kids|"
                     r"executive|executives|businessman|businesswoman|customer|customers|audience)\b", re.I)


def check_photo_prompt(text: str) -> tuple[bool, str]:
    """Photo style is for places and things only: a realistic face in a documentary reads as a real person."""
    ok, why = check_prompt(text)
    if not ok:
        return ok, why
    if _PEOPLE.search(text):
        return False, ("Photo style can't show people: a realistic face in a documentary looks like a real person. "
                       "Describe a place or object, or switch to Ink for people.")
    return True, ""


def prompt_for(query: str) -> str:
    subject = re.sub(r"\b(stock footage|footage|b-roll|slow motion|fast motion|close up of|animation of|animated)\b",
                     "", query, flags=re.I)
    subject = re.sub(r"\s+", " ", subject).strip(" ,.-")
    return f"{subject}, {cfg()['style'].strip()}"


# ──────────────────────────── queueing (dashboard side) ────────────────────────────

def candidates_for(manifest: dict) -> list[str]:
    """Beat ids that may be illustrated and don't have AI options yet."""
    out = []
    for b in manifest.get("beats", []):
        ok, _ = eligible(b["type"], b["query"])
        if ok and not any(c["source"] == "ai" for c in b["candidates"]):
            out.append(b["id"])
    return out


# ──────────────────────────── the Kaggle notebook ────────────────────────────

KERNEL_TEMPLATE = r'''
# Generated by docu-pipeline. Draws illustrations for abstract beats with SDXL.
import json, os, subprocess, sys, time, traceback

JOB = json.loads(r"""__JOB__""")
OUT = "/kaggle/working"
started = time.time()
made = {}


def save(error=None):
    # Written after every beat, so a crash halfway still hands back what was drawn.
    json.dump({"made": made, "seconds": round(time.time() - started), "error": error},
              open(os.path.join(OUT, "result.json"), "w"))


try:
    import torch
    # Check the GPU before downloading 6 GB of model: no GPU, or one this torch can't drive (P100).
    if not torch.cuda.is_available():
        raise RuntimeError("No GPU on this session. Kaggle GPU needs a phone-verified account and weekly quota left.")
    name = torch.cuda.get_device_name(0)
    print(f"GPU: {name}, torch {torch.__version__}", flush=True)
    torch.zeros(1, device="cuda").add_(1)  # fails fast with "no kernel image" on unsupported cards

    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "diffusers>=0.27", "accelerate"], check=False)
    from diffusers import AutoencoderKL, StableDiffusionXLPipeline

    vae = AutoencoderKL.from_pretrained(JOB["vae"], torch_dtype=torch.float16)

    def load(model):
        try:
            p = StableDiffusionXLPipeline.from_pretrained(model, vae=vae, torch_dtype=torch.float16,
                                                          variant="fp16", use_safetensors=True)
        except Exception:  # some fine-tunes only publish full-precision files
            p = StableDiffusionXLPipeline.from_pretrained(model, vae=vae, torch_dtype=torch.float16,
                                                          use_safetensors=True)
        p.set_progress_bar_config(disable=True)
        return p.to("cuda")

    # One model at a time (a T4 can't hold two): ink items on the base model, photo items on the
    # photoreal fine-tune, falling back to the base model if that one won't load.
    for model in dict.fromkeys(item.get("model", JOB["model"]) for item in JOB["items"]):
        try:
            pipe = load(model)
        except Exception as e:
            print(f"couldn't load {model} ({e}); using {JOB['model']}", flush=True)
            pipe = load(JOB["model"])
        print(f"{model} loaded ({time.time() - started:.0f}s)", flush=True)
        for item in [i for i in JOB["items"] if i.get("model", JOB["model"]) == model]:
            made[item["id"]] = []
            for k in range(JOB["per_beat"]):
                g = torch.Generator("cuda").manual_seed(item["seed"] + k)
                img = pipe(item["prompt"], negative_prompt=item.get("negative", JOB["negative"]),
                           width=JOB["width"], height=JOB["height"], num_inference_steps=JOB["steps"],
                           guidance_scale=item.get("guidance", JOB["guidance"]), generator=g).images[0]
                fname = f"{item['id']}-{k}.jpg"
                img.save(os.path.join(OUT, fname), quality=88)
                made[item["id"]].append(fname)
            save()
            print(f"{item['id']}: done ({time.time() - started:.0f}s)", flush=True)
        del pipe
        torch.cuda.empty_cache()
    save()
except Exception as e:
    traceback.print_exc()
    save(f"{e.__class__.__name__}: {e}"[:400])
    # Exit cleanly: the error travels back in result.json together with anything already drawn.
'''


def build_kernel(folder: Path, items: list[dict], username: str, suffix: str = "") -> str:
    c = cfg()
    job = {"model": c["model"], "vae": c["vae"], "per_beat": c["per_beat"], "steps": c["steps"],
           "guidance": c["guidance"], "width": c["width"], "height": c["height"],
           "negative": c["negative"].strip(), "items": items}
    code = KERNEL_TEMPLATE.replace("__JOB__", json.dumps(job).replace('"""', r'\"\"\"'))
    (folder / "illustrate.py").write_text(code, encoding="utf-8")
    slug = c["kernel_slug"] + (f"-{re.sub(r'[^a-z0-9]+', '-', suffix.lower())[:30].strip('-')}" if suffix else "")
    kernel_id = f"{username}/{slug}"
    (folder / "kernel-metadata.json").write_text(json.dumps({
        "id": kernel_id, "title": slug, "code_file": "illustrate.py",
        "language": "python", "kernel_type": "script", "is_private": True,
        "enable_gpu": True, "enable_internet": True, "machine_shape": c.get("accelerator", "NvidiaTeslaT4"),
        "dataset_sources": [], "competition_sources": [], "kernel_sources": [], "model_sources": [],
    }, indent=2), encoding="utf-8")
    return kernel_id


def _api():
    username = env("KAGGLE_USERNAME")
    if not (username and env("KAGGLE_API_TOKEN")):
        raise IllustrateError("Kaggle isn't connected. Add KAGGLE_USERNAME and KAGGLE_API_TOKEN as "
                              "GitHub repository secrets (Settings → Secrets and variables → Actions).")
    from kaggle.api.kaggle_api_extended import KaggleApi  # installed on the worker only
    api = KaggleApi()
    api.authenticate()
    return api, username


def push(items: list[dict], slug: str) -> str:
    """Send the notebook to Kaggle. Returns its id. One notebook per story, so two stories
    drawing at once never overwrite each other's output."""
    api, username = _api()
    with tempfile.TemporaryDirectory() as tmp:
        kernel_id = build_kernel(Path(tmp), items, username, suffix=slug)
        print(f"  pushing {kernel_id} with {len(items)} beats on {cfg().get('accelerator', 'NvidiaTeslaT4')}")
        try:
            api.kernels_push(tmp)
        except Exception as e:  # an accelerator name Kaggle doesn't know: fall back to plain "any GPU"
            print(f"  push with accelerator failed ({e}); retrying with the default GPU")
            meta_file = Path(tmp) / "kernel-metadata.json"
            meta = json.loads(meta_file.read_text())
            meta.pop("machine_shape", None)
            meta_file.write_text(json.dumps(meta))
            api.kernels_push(tmp)
    return kernel_id


def status(kernel_id: str) -> tuple[str, str]:
    """('queued' | 'running' | 'complete' | 'error', failure message)."""
    api, _ = _api()
    resp = api.kernels_status(kernel_id)
    raw = str(getattr(resp, "status", resp)).lower()
    for word in ("complete", "error", "cancel", "running", "queued"):
        if word in raw:
            return ("error" if word == "cancel" else word), (getattr(resp, "failure_message", "") or "")
    return raw, ""


def wait(kernel_id: str, seconds: float, on_status=None) -> tuple[str, str]:
    """Poll until Kaggle finishes or `seconds` pass. Returns the last (state, failure)."""
    deadline = time.time() + seconds
    state, failure, last = "queued", "", None
    while time.time() < deadline:
        time.sleep(30)
        try:
            state, failure = status(kernel_id)
        except Exception as e:  # a flaky status call isn't a failed notebook
            print(f"  kaggle status check failed ({e}); trying again")
            continue
        if state != last:
            print(f"  kaggle: {state}")
            last = state
            if on_status:
                on_status(state)
        if state in ("complete", "error"):
            break
    return state, failure


def collect(kernel_id: str, out_dir: Path, state: str, failure: str = "") -> dict:
    """Download what the notebook made. Raises with Kaggle's own error when there's nothing."""
    api, _ = _api()
    try:
        api.kernels_output(kernel_id, str(out_dir))
    except Exception as e:
        print(f"  couldn't download notebook output: {e}")
    result_file = out_dir / "result.json"
    result = json.loads(result_file.read_text()) if result_file.exists() else {}
    made = {beat_id: [out_dir / name for name in names if (out_dir / name).exists()]
            for beat_id, names in (result.get("made") or {}).items()}
    made = {k: v for k, v in made.items() if v}

    reason = result.get("error") or failure or ("" if state == "complete" else f"status {state}")
    if not reason and not made:
        reason = "it finished but returned no images"
    if reason and not made:
        tail = _log_tail(out_dir)
        print("  ---- kaggle log (tail) ----\n" + tail)
        raise IllustrateError(f"The Kaggle notebook failed: {reason}"
                              + (f" | log: {tail[-300:]}" if tail and not result.get("error") else "")
                              + f" — full log at kaggle.com/code/{kernel_id}")
    if reason:
        print(f"  partial result, notebook stopped early: {reason}")
    return made


def _log_tail(out_dir: Path, lines: int = 25) -> str:
    """Kaggle's log is a JSON list of {stream_name, data}; flatten it and keep the end."""
    logs = list(out_dir.glob("*.log"))
    if not logs:
        return ""
    raw = logs[0].read_text(errors="replace")
    try:
        text = "".join(chunk.get("data", "") for chunk in json.loads(raw))
    except (ValueError, AttributeError):
        text = raw
    return "\n".join(text.strip().splitlines()[-lines:])


def _demo_images(items: list[dict], out_dir: Path) -> dict:
    """Demo/tests: stand-in images instead of a Kaggle run."""
    import shutil
    from .config import ROOT
    samples = sorted((ROOT / "web" / "demo").glob("sample*.jpg"))
    out = {}
    for n, item in enumerate(items):
        out[item["id"]] = []
        for k in range(cfg()["per_beat"]):
            dest = out_dir / f"{item['id']}-{k}.jpg"
            shutil.copy(samples[(n + k) % len(samples)], dest)
            out[item["id"]].append(dest)
    return out


# ──────────────────────────── storing results ────────────────────────────

def store(slug: str, images: dict[str, list[Path]], prompts: dict[str, str] | None = None,
          styles: dict[str, str] | None = None) -> int:
    """Add the images to each beat as 'AI illustration' options. Doesn't change your picks."""
    ep = Episode.load(slug)
    m = ep.read("visuals.json")
    added = 0
    for b in m.get("beats", []):
        start = sum(1 for c in b["candidates"] if c["source"] == "ai")  # a redraw adds, never replaces
        for k, path in enumerate(images.get(b["id"], []), start=start):
            file = f"visuals/ai/{b['id']}-{k}.b64"
            ep.write(file, "image/jpeg;" + base64.b64encode(path.read_bytes()).decode())
            b["candidates"] = [c for c in b["candidates"] if c.get("file") != file]
            # after real picks and uploads, before the fallback card
            card_at = next((i for i, c in enumerate(b["candidates"]) if c["source"] == "card"), len(b["candidates"]))
            photo = (styles or {}).get(b["id"]) == "photo"
            b["candidates"].insert(card_at, {
                "source": "ai", "kind": "image", "file": file, "style": "photo" if photo else "ink",
                "title": "AI photo-style image" if photo else "AI illustration",
                "credit": "AI image (RealVisXL)" if photo else "AI illustration (SDXL)",
                "license": "CreativeML OpenRAIL++-M",
                "prompt": (prompts or {}).get(b["id"]) or prompt_for(b["query"]),
            })
            if b["chosen"] >= card_at:
                b["chosen"] += 1  # keep pointing at the same option you had picked
            added += 1
    ep.write("visuals.json", m)
    return added


def _set(slug: str, **fields) -> dict:
    ep = Episode(slug)
    meta = ep.read("meta.json")
    meta["illustrate"] = {**(meta.get("illustrate") or {}), **fields}
    ep.write("meta.json", meta)
    return meta["illustrate"]


def _finish(slug: str, kernel_id: str | None, state: str, failure: str, used: dict, started: float,
            items: list[dict] | None = None, styles: dict | None = None) -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        if os.getenv("DOCU_MOCK_ILLUSTRATE") == "1":
            images = _demo_images(items or [{"id": b} for b in used], Path(tmp))
        else:
            images = collect(kernel_id, Path(tmp), state, failure)
        added = store(slug, images, used, styles)
    job = _set(slug, state="done", added=added, kaggle_status="complete",
               seconds_taken=round(time.time() - started))
    print(f"  ✓ {added} illustrations added ({time.time() - started:.0f}s)")
    return job


def run(slug: str, beat_ids: list[str], prompts: dict[str, str] | None = None,
        styles: dict[str, str] | None = None) -> dict:
    """prompts: {beat_id: your own wording} for beats you drew one at a time from the Pictures tab."""
    ep = Episode.load(slug)
    m = ep.read("visuals.json") or {}
    beats = {b["id"]: b for b in m.get("beats", [])}
    prompts, styles = prompts or {}, styles or {}
    c = cfg()
    items, used, photo_ids = [], {}, {}
    for i, bid in enumerate(beat_ids):
        b = beats.get(bid)
        if not b:
            continue
        # Re-checked here: the queue can't be used to slip a real-world beat or a named prompt through.
        photo = styles.get(bid) == "photo" and bid in prompts
        if photo:
            if not check_photo_prompt(prompts[bid])[0]:
                continue
            prompt = f"{prompts[bid].strip()}, {c['photo_style'].strip()}"
        elif bid in prompts:
            if not check_prompt(prompts[bid])[0]:
                continue
            prompt = f"{prompts[bid].strip()}, {c['style'].strip()}"
        elif eligible(b["type"], b["query"])[0]:
            prompt = prompt_for(b["query"])
        else:
            continue
        drawn_before = sum(1 for c in b["candidates"] if c["source"] == "ai")
        item = {"id": bid, "prompt": prompt, "seed": 1000 + i * 17 + drawn_before * 101}
        if photo:
            item.update(model=c["photo_model"], negative=c["photo_negative"].strip(), guidance=c["photo_guidance"])
        items.append(item)
        used[bid] = prompt
        if photo:
            photo_ids[bid] = "photo"
    if not items:
        raise IllustrateError("None of those beats can be illustrated.")
    started = time.time()
    print(f"[illustrate] {ep.read('meta.json')['topic']}: {len(items)} beats")
    if os.getenv("DOCU_MOCK_ILLUSTRATE") == "1":
        return _finish(slug, None, "complete", "", used, started, items, photo_ids)

    kernel_id = push(items, slug)
    _set(slug, kernel=kernel_id, pushed_at=datetime.now(timezone.utc).isoformat(), used=used,
         styles=photo_ids, kaggle_status="queued")
    state, failure = wait(kernel_id, KAGGLE_TIMEOUT, on_status=lambda s: _set(slug, kaggle_status=s))
    if state in ("complete", "error"):
        return _finish(slug, kernel_id, state, failure, used, started, styles=photo_ids)
    # Kaggle's free GPU queue is slow today. Don't throw the work away: the next worker run
    # picks the pictures up when the notebook finishes.
    print(f"  Kaggle still {state} after {KAGGLE_TIMEOUT // 60} min; the next worker run collects the pictures")
    return _set(slug, state="waiting", kaggle_status=state)


def waiting() -> list[str]:
    return [slug for slug, files in Episode.read_many(["meta.json"]).items()
            if ((files.get("meta.json") or {}).get("illustrate") or {}).get("state") == "waiting"]


def collect_waiting(max_wait: float = 15 * 60) -> tuple[int, int]:
    """Worker: check on notebooks still drawing from an earlier run, store what finished."""
    done = failed = 0
    for slug in waiting():
        job = (Episode(slug).read("meta.json") or {}).get("illustrate") or {}
        kernel_id, used = job.get("kernel"), job.get("used") or {}
        pushed = datetime.fromisoformat(job["pushed_at"]) if job.get("pushed_at") else datetime.now(timezone.utc)
        age_h = (datetime.now(timezone.utc) - pushed).total_seconds() / 3600
        print(f"[illustrate] checking on {kernel_id} ({age_h:.1f} h since it was sent)")
        try:
            state, failure = wait(kernel_id, max_wait, on_status=lambda s, slug=slug: _set(slug, kaggle_status=s))
            if state in ("complete", "error"):
                _finish(slug, kernel_id, state, failure, used, time.time(), styles=job.get("styles"))
                done += 1
            elif age_h > 6:
                raise IllustrateError("Kaggle never got to it (6 hours in its queue). Try again later.")
        except Exception as e:
            _set(slug, state="error", error=str(e)[:500])
            failed += 1
    return done, failed
