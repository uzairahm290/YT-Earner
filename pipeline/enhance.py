"""Enhance a recording of your own voice: same voice, just clearer.

Used by the Voice studio's "Enhance my recording". The voice itself is never changed:
  Kaggle GPU   Demucs pulls the voice away from everything else (fan, traffic, music, TV),
               a gentle hiss reduction, and other people talking get muted (not cut, so your
               timing stays exactly as recorded)
  worker       a light "proper mic" polish: rumble filter, less boxiness, a touch of presence,
               gentle compression, de-essing, and YouTube loudness (-16 LUFS)
"""
from __future__ import annotations

import subprocess
from pathlib import Path

MAX_BYTES = 30 * 1024 * 1024   # about 30 minutes of phone M4A
MAX_SECONDS = 45 * 60

# The polish after the GPU cleanup. Kept gentle: it should sound like you on a good mic, not "processed".
POLISH = ("highpass=f=75,"
          "equalizer=f=250:t=q:w=1.2:g=-2.5,"     # less boxy room tone
          "equalizer=f=3200:t=q:w=1.4:g=2,"       # a little presence, easier to understand
          "equalizer=f=7000:t=q:w=2:g=-1.5,"      # soften harsh S sounds
          "acompressor=threshold=-21dB:ratio=2.5:attack=8:release=160:makeup=2,"
          "alimiter=limit=0.89,"
          "loudnorm=I=-16:TP=-1.5:LRA=11")


def prepare(src: Path, out: Path) -> float:
    """Any upload (M4A, MP3, WAV, a phone video) → mono 44.1 kHz FLAC for Kaggle. Returns seconds."""
    r = subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(src), "-vn", "-ac", "1", "-ar", "44100",
                        "-t", str(MAX_SECONDS), "-c:a", "flac", str(out)], capture_output=True, text=True)
    if r.returncode != 0 or not out.exists():
        raise ValueError(f"Couldn't read that recording: {r.stderr.strip()[-200:]}")
    p = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(out)],
                       capture_output=True, text=True)
    try:
        return float(p.stdout.strip())
    except ValueError:
        return 0.0


def polish_to_mp3(wav: Path, out: Path) -> Path:
    r = subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(wav), "-af", POLISH, "-ar", "44100", "-ac", "1",
                        "-c:a", "libmp3lame", "-b:a", "192k", str(out)], capture_output=True, text=True)
    if r.returncode != 0:
        raise ValueError(f"The final polish failed: {r.stderr.strip()[-300:]}")
    return out


KERNEL = r'''
# Generated by docu-pipeline: makes a recording of the creator's voice clearer, without changing the voice.
import glob, json, os, subprocess, sys, time, traceback
OUT = "/kaggle/working"
TMP = "/kaggle/tmp"
os.makedirs(TMP, exist_ok=True)
JOB = json.loads("""__JOB__""")
started = time.time()
report = {"steps": [], "skipped": []}

def save(error=None):
    report.update(error=error, seconds=round(time.time() - started))
    json.dump(report, open(os.path.join(OUT, "result.json"), "w"))

try:
    import torch
    if not torch.cuda.is_available():
        raise RuntimeError("No GPU on this session. Kaggle GPU needs a phone-verified account and weekly quota left.")
    pip = [sys.executable, "-m", "pip", "install", "-q"]
    subprocess.run(pip + ["demucs", "noisereduce", "speechbrain", "soundfile", "librosa"], check=False)
    import librosa, numpy as np, soundfile
    src = glob.glob("/kaggle/input/**/input.flac", recursive=True)[0]
    y_orig, sr = librosa.load(src, sr=44100, mono=True)
    report["total_s"] = round(len(y_orig) / sr, 1)

    # 1. Demucs: the voice, separated from everything that isn't a voice.
    y = y_orig
    try:
        subprocess.run([sys.executable, "-m", "demucs", "-n", "htdemucs", "--two-stems", "vocals", "-d", "cuda",
                        "-o", os.path.join(TMP, "sep"), src], check=True)
        v, _ = librosa.load(glob.glob(os.path.join(TMP, "sep", "**", "vocals.wav"), recursive=True)[0], sr=sr, mono=True)
        y = v[:len(y_orig)]
        report["steps"].append("background sounds removed")
    except Exception as e:
        report["skipped"].append(f"background removal: {e}"[:200])

    # 2. Leftover hiss, gently (strong settings make a voice sound underwater).
    try:
        import noisereduce as nr
        y = nr.reduce_noise(y=y, sr=sr, stationary=True, prop_decrease=0.6)
        report["steps"].append("hiss reduced")
    except Exception as e:
        report["skipped"].append(f"hiss reduction: {e}"[:200])

    # 3. Other people talking: muted where only they speak. A moment is muted only when no window
    #    that sounds like you covers it, so your own words are never lost.
    if JOB.get("mute_others", True):
        try:
            y16 = librosa.resample(y, orig_sr=sr, target_sr=16000)
            fs = int(0.03 * 16000)
            n = len(y16) // fs
            energy = (y16[: n * fs].reshape(n, fs) ** 2).mean(1)
            speech = energy > max(np.percentile(energy, 20) * 6, 1e-7)
            win, hop = int(1.5 / 0.03), int(0.5 / 0.03)
            starts = [i for i in range(0, max(1, n - win + 1), hop) if speech[i:i + win].mean() > 0.4]
            if len(starts) >= 6:
                try:
                    from speechbrain.inference.classifiers import EncoderClassifier
                except ImportError:
                    from speechbrain.pretrained import EncoderClassifier
                enc = EncoderClassifier.from_hparams(source="speechbrain/spkrec-ecapa-voxceleb",
                                                     savedir=os.path.join(TMP, "ecapa"), run_opts={"device": "cuda"})
                embs = []
                for i in starts:
                    seg = torch.tensor(y16[i * fs:(i + win) * fs]).unsqueeze(0).to("cuda")
                    e = enc.encode_batch(seg).squeeze().detach().cpu().numpy()
                    embs.append(e / (np.linalg.norm(e) + 1e-9))
                embs = np.array(embs)
                centre = embs.mean(0)
                for _ in range(3):  # settle on the majority voice: yours
                    centre /= np.linalg.norm(centre) + 1e-9
                    sims = embs @ centre
                    centre = embs[sims >= max(0.4, float(np.median(sims)) - 0.15)].mean(0)
                centre /= np.linalg.norm(centre) + 1e-9
                sims = embs @ centre
                ok = sims >= max(0.4, float(np.median(sims)) - 0.2)
                yours, theirs = np.zeros(n, bool), np.zeros(n, bool)
                for s, good in zip(starts, ok):
                    (yours if good else theirs)[s:s + win] = True
                mute = theirs & ~yours
                if mute.any():
                    gain16 = np.repeat(np.where(mute, 0.0, 1.0), fs)
                    gain16 = np.convolve(gain16, np.ones(800) / 800, mode="same")  # 50 ms fades
                    gain = np.interp(np.arange(len(y)) * 16000 / sr, np.arange(len(gain16)), gain16, right=1.0)
                    y = y * gain
                report["steps"].append(f"other voices muted ({mute.sum() * 0.03:.0f} s)" if mute.any()
                                       else "no other voices found")
        except Exception as e:
            report["skipped"].append(f"other voices: {e}"[:200])

    y = y / (np.abs(y).max() + 1e-9) * 0.8
    soundfile.write(os.path.join(OUT, "enhanced.wav"), y.astype(np.float32), sr, subtype="PCM_16")
    save()
except Exception as e:
    traceback.print_exc()
    save(f"{e.__class__.__name__}: {e}"[:400])
'''
