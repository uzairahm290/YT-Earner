"""Make an AI narrator for story videos: a made-up person, never a real one.

You describe the narrator in the dashboard ("English businessman in his 40s, navy suit, arms
crossed"). The worker sends one Kaggle GPU notebook that
  1. draws a few photoreal candidates with RealVisXL (same photo model as the picture desk), on a
     plain studio backdrop so the cutout is clean, and
  2. cuts each one out (rembg with a portrait background-removal model),
then you pick one and it becomes the narrator, marked AI-generated so YouTube uploads say so.

State lives in _settings/persona/gen.json; candidates in _settings/persona/gen/<k>.jpg|png.b64.
"""
from __future__ import annotations

import base64
import json
import os
import re
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path

from .config import load_config
from .store import get_store
from . import persona

SETTINGS = "_settings"
STATE = "persona/gen.json"
KERNEL_NAME = "docu-narrator"
CANDIDATES = 6
KAGGLE_WAIT = 40 * 60

DEFAULT = "English businessman in his early 40s, short neat brown hair, clean-shaven, navy blue suit, " \
          "white shirt, dark tie, arms crossed, confident slight smile"

STYLE = ("professional corporate portrait photograph, waist-up, facing the camera, plain light grey studio "
         "backdrop, soft even studio lighting, 85mm lens, sharp focus, natural skin texture, photorealistic")
NEGATIVE = ("cartoon, illustration, painting, 3d render, cgi, deformed hands, extra fingers, extra arms, "
            "fused fingers, text, letters, logo, watermark, badge, name tag, celebrity, famous person, "
            "busy background, office background, cropped head, out of frame, blurry, lowres, oversaturated")

# Words that would aim the picture at a real, identifiable person.
_REAL = re.compile(r"\b(looks? like|resembl\w*|celebrity|famous|actor|president|prime minister|king|"
                   r"elon|musk|trump|biden|obama|sunak|starmer|bezos|gates)\b", re.I)


class NarratorGenError(ValueError):
    pass


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def info() -> dict:
    raw = get_store().read(SETTINGS, STATE)
    return json.loads(raw) if raw else {}


def _set(**fields) -> dict:
    job = {**info(), **fields}
    get_store().write(SETTINGS, STATE, json.dumps(job))
    return job


def request(description: str, name: str = "Narrator") -> dict:
    description = re.sub(r"\s+", " ", (description or "").strip()) or DEFAULT
    if len(description) > 300:
        raise NarratorGenError("Keep the description under 300 characters.")
    if _REAL.search(description):
        raise NarratorGenError("Describe a made-up person. The narrator can't be or look like a real one.")
    return _set(state="queued", description=description, name=(name or "Narrator").strip()[:40],
                requested_at=_now(), error=None, kernel=None, kaggle_status=None, candidates=[])


def pending() -> bool:
    return info().get("state") in ("queued", "waiting")


def resume_abandoned() -> bool:
    """Worker start: 'running' means a stopped worker left it (only one worker runs at a time)."""
    job = info()
    if job.get("state") != "running":
        return False
    _set(state="waiting" if job.get("kernel") else "queued")
    return True


def candidate(k: int, kind: str = "jpg") -> bytes | None:
    data = get_store().read(SETTINGS, f"persona/gen/{k}.{kind}.b64")
    return base64.b64decode(data) if data else None


def use(k: int, name: str | None = None) -> dict:
    """Make candidate k the narrator (the cutout; marked AI-generated)."""
    png = candidate(k, "png")
    if not png:
        raise NarratorGenError("That picture isn't there any more. Make new ones.")
    meta = persona.save(png, name or info().get("name") or "Narrator", ai_generated=True)
    _set(chosen=k)
    return meta


# ──────────────────────────── the Kaggle notebook ────────────────────────────

KERNEL = r'''
# Generated by docu-pipeline: draws a made-up narrator for story videos and cuts them out.
import json, os, subprocess, sys, time, traceback
JOB = json.loads(r"""__JOB__""")
OUT = "/kaggle/working"
started = time.time()
made = []

def save(error=None):
    json.dump({"made": made, "error": error, "seconds": round(time.time() - started)},
              open(os.path.join(OUT, "result.json"), "w"))

try:
    import torch
    if not torch.cuda.is_available():
        raise RuntimeError("No GPU on this session. Kaggle GPU needs a phone-verified account and weekly quota left.")
    torch.zeros(1, device="cuda").add_(1)
    pip = [sys.executable, "-m", "pip", "install", "-q"]
    subprocess.run(pip + ["diffusers>=0.27", "accelerate"], check=False)
    from diffusers import AutoencoderKL, StableDiffusionXLPipeline
    vae = AutoencoderKL.from_pretrained(JOB["vae"], torch_dtype=torch.float16)
    try:
        pipe = StableDiffusionXLPipeline.from_pretrained(JOB["model"], vae=vae, torch_dtype=torch.float16,
                                                         variant="fp16", use_safetensors=True)
    except Exception:
        pipe = StableDiffusionXLPipeline.from_pretrained(JOB["model"], vae=vae, torch_dtype=torch.float16,
                                                         use_safetensors=True)
    pipe.set_progress_bar_config(disable=True)
    pipe = pipe.to("cuda")
    print(f"model loaded ({time.time() - started:.0f}s)", flush=True)
    for k in range(JOB["count"]):
        g = torch.Generator("cuda").manual_seed(JOB["seed"] + k * 101)
        img = pipe(JOB["prompt"], negative_prompt=JOB["negative"], width=832, height=1216,
                   num_inference_steps=JOB["steps"], guidance_scale=JOB["guidance"], generator=g).images[0]
        img.save(os.path.join(OUT, f"{k}.jpg"), quality=92)
        made.append(k)
        save()
        print(f"picture {k + 1}/{JOB['count']} ({time.time() - started:.0f}s)", flush=True)
    del pipe
    torch.cuda.empty_cache()

    # Cut each one out. The portrait model keeps hair and suit edges clean.
    subprocess.run(pip + ["rembg[gpu]"], check=False)
    from rembg import new_session, remove
    from PIL import Image
    session = None
    for model in ("birefnet-portrait", "isnet-general-use", "u2net_human_seg"):
        try:
            session = new_session(model)
            print(f"cutout model: {model}", flush=True)
            break
        except Exception as e:
            print(f"cutout model {model} unavailable: {e}", flush=True)
    for k in made:
        im = Image.open(os.path.join(OUT, f"{k}.jpg")).convert("RGB")
        cut = remove(im, session=session, post_process_mask=True) if session else remove(im)
        cut.save(os.path.join(OUT, f"{k}.png"))
    save()
except Exception as e:
    traceback.print_exc()
    save(f"{e.__class__.__name__}: {e}"[:400])
'''


def _push(job: dict) -> str:
    from .illustrate import _api
    api, user = _api()
    kernel_id = f"{user}/{KERNEL_NAME}"
    with tempfile.TemporaryDirectory() as d:
        d = Path(d)
        (d / "job.py").write_text(KERNEL.replace("__JOB__", json.dumps(job)), encoding="utf-8")
        meta = {"id": kernel_id, "title": KERNEL_NAME, "code_file": "job.py", "language": "python",
                "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
                "machine_shape": load_config()["illustrate"].get("accelerator", "NvidiaTeslaT4"),
                "dataset_sources": [], "competition_sources": [], "kernel_sources": [], "model_sources": []}
        (d / "kernel-metadata.json").write_text(json.dumps(meta))
        try:
            api.kernels_push(str(d))
        except Exception as e:
            if "409" in str(e):  # an earlier run is still busy on Kaggle: use a fresh name
                kernel_id = f"{user}/{KERNEL_NAME}-{datetime.now(timezone.utc):%m%d%H%M%S}"
                meta.update(id=kernel_id, title=kernel_id.split("/")[1])
            else:
                meta.pop("machine_shape")
            (d / "kernel-metadata.json").write_text(json.dumps(meta))
            api.kernels_push(str(d))
    return kernel_id


def _store_candidates(folder: Path) -> list[int]:
    store, kept = get_store(), []
    for k in range(CANDIDATES):
        jpg, png = folder / f"{k}.jpg", folder / f"{k}.png"
        if jpg.exists() and png.exists():
            store.write(SETTINGS, f"persona/gen/{k}.jpg.b64", base64.b64encode(jpg.read_bytes()).decode())
            store.write(SETTINGS, f"persona/gen/{k}.png.b64", base64.b64encode(png.read_bytes()).decode())
            kept.append(k)
        else:
            store.write(SETTINGS, f"persona/gen/{k}.jpg.b64", "")
            store.write(SETTINGS, f"persona/gen/{k}.png.b64", "")
    return kept


def _mock(folder: Path) -> None:
    """Tests: stand-in pictures instead of a GPU."""
    from PIL import Image, ImageDraw
    for k in range(3):
        im = Image.new("RGB", (416, 608), (200, 202, 205))
        ImageDraw.Draw(im).ellipse((140, 80, 280, 240), fill=(150, 110, 90))
        im.save(folder / f"{k}.jpg")
        cut = Image.new("RGBA", im.size, (0, 0, 0, 0))
        ImageDraw.Draw(cut).ellipse((140, 80, 280, 240), fill=(150, 110, 90, 255))
        ImageDraw.Draw(cut).rectangle((110, 240, 310, 608), fill=(30, 40, 70, 255))
        cut.save(folder / f"{k}.png")


def run() -> dict:
    """Worker: push the notebook (or check on the one already there) and store the pictures."""
    job = info()
    started = time.time()
    try:
        if job.get("state") == "queued":
            print(f"[narrator] drawing: {job['description']}")
            _set(state="running", started_at=_now(), error=None)
            if os.getenv("DOCU_MOCK_NARRATOR") == "1":
                with tempfile.TemporaryDirectory() as d:
                    _mock(Path(d))
                    kept = _store_candidates(Path(d))
                return _set(state="done", candidates=kept, finished_at=_now())
            c = load_config()["illustrate"]
            seed = int(time.time()) % 100000
            kernel_id = _push({"model": c["photo_model"], "vae": c["vae"], "steps": max(30, c.get("steps", 30)),
                               "guidance": c.get("photo_guidance", 5.0), "count": CANDIDATES, "seed": seed,
                               "prompt": f"{job['description']}, {STYLE}", "negative": NEGATIVE})
            _set(kernel=kernel_id, kaggle_status="queued", pushed_at=_now())
            wait_s = KAGGLE_WAIT
        else:
            kernel_id, wait_s = job["kernel"], 15 * 60
        from .illustrate import _api, _log_tail, wait
        state, _ = wait(kernel_id, wait_s, on_status=lambda s: _set(kaggle_status=s))
        if state not in ("complete", "error"):
            pushed = datetime.fromisoformat(info().get("pushed_at") or _now())
            if (datetime.now(timezone.utc) - pushed).total_seconds() > 6 * 3600:
                raise NarratorGenError("Kaggle never got to it (6 hours in its queue). Try again later.")
            return _set(state="waiting", kaggle_status=state)
        api, _ = _api()
        with tempfile.TemporaryDirectory() as d:
            d = Path(d)
            try:
                api.kernels_output(kernel_id, str(d))
            except Exception as e:
                print(f"  couldn't download notebook output: {e}")
            report = json.loads((d / "result.json").read_text()) if (d / "result.json").exists() else {}
            kept = _store_candidates(d)
            if not kept:
                raise NarratorGenError(f"No pictures came back: {report.get('error') or 'unknown error'} | "
                                       f"{_log_tail(d)[-250:]} (log at kaggle.com/code/{kernel_id})")
        print(f"  ✓ {len(kept)} narrator pictures in {time.time() - started:.0f}s")
        return _set(state="done", candidates=kept, finished_at=_now(), error=None)
    except Exception as e:
        import traceback
        traceback.print_exc()
        return _set(state="error", error=f"{type(e).__name__}: {e}"[:400])
