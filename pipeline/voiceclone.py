def clean_info() -> dict:
    return (reference_info() or {}).get("clean") or {}


def _set_clean(**fields) -> dict:
    meta = reference_info() or {}
    meta["clean"] = {**(meta.get("clean") or {}), **fields}
    get_store().write(SETTINGS, "voiceref/meta.json", json.dumps(meta))
    return meta["clean"]


def clean_pending() -> bool:
    return clean_info().get("state") in ("queued", "waiting")


def resume_abandoned_clean() -> bool:
    """Worker start: only one worker runs at a time, so a cleanup still marked 'running' belongs to a
    worker that was stopped. Pick it up again: collect it if it reached Kaggle, otherwise start over."""
    job = clean_info()
    if job.get("state") != "running":
        return False
    _set_clean(state="waiting" if job.get("kernel") else "queued")
    return True


def clean_reference() -> dict:
    """Worker: send the voice sample to Kaggle for cleanup (or collect a cleanup still running)."""
    job = clean_info()
    started = time.time()
    try:
        if job.get("state") == "queued":
            print("[voice sample] cleaning on Kaggle")
            _set_clean(state="running", started_at=datetime.now(timezone.utc).isoformat(), error=None)
            with tempfile.TemporaryDirectory() as d:
                d = Path(d)
                raw = reference_wav(d, prefer_clean=False, sample_rate=44100, light=True)
                if os.getenv("DOCU_MOCK_VOICECLONE") == "1":
                    _store_clean(raw.read_bytes(), {"steps": ["(demo: not cleaned)"], "skipped": [], "kept_s": 0})
                    return clean_info()
                kernel_id = _push_kaggle("docu-voice-clean", {"ref.wav": raw}, CLEAN_KERNEL)
            _set_clean(kernel=kernel_id, kaggle_status="queued", pushed_at=datetime.now(timezone.utc).isoformat())
            wait_s = KAGGLE_WAIT
        else:
            kernel_id = job["kernel"]
            wait_s = 15 * 60
        from .illustrate import wait
        state, _ = wait(kernel_id, wait_s, on_status=lambda s: _set_clean(kaggle_status=s))
        if state not in ("complete", "error"):
            pushed = datetime.fromisoformat(clean_info().get("pushed_at") or datetime.now(timezone.utc).isoformat())
            if (datetime.now(timezone.utc) - pushed).total_seconds() > 6 * 3600:
                raise CloneError("Kaggle never got to it (6 hours in its queue). Upload the sample again later.")
            return _set_clean(state="waiting", kaggle_status=state)
        with tempfile.TemporaryDirectory() as d:
            d = Path(d)
            api, _ = _api()
            try:
                api.kernels_output(kernel_id, str(d))
            except Exception as e:
                print(f"  couldn't download notebook output: {e}")
            report = json.loads((d / "result.json").read_text()) if (d / "result.json").exists() else {}
            if report.get("error") or not (d / "clean.wav").exists():
                from .illustrate import _log_tail
                raise CloneError(f"Cleanup failed: {report.get('error') or 'no audio came back'} | {_log_tail(d)[-250:]}")
            _store_clean((d / "clean.wav").read_bytes(), report)
        print(f"  ✓ voice sample cleaned in {time.time() - started:.0f}s")
        return clean_info()
    except Exception as e:
        import traceback
        traceback.print_exc()
        return _set_clean(state="error", error=f"{type(e).__name__}: {e}"[:400])


def _store_clean(wav: bytes, report: dict) -> None:
    get_store().write(SETTINGS, "voiceref/clean.b64", "audio/wav;" + base64.b64encode(wav).decode())
    _set_clean(state="done", finished_at=datetime.now(timezone.utc).isoformat(), steps=report.get("steps", []),
               skipped=report.get("skipped", []), kept_s=report.get("kept_s"), total_s=report.get("total_s"),
               error=None)


def chunks(beats: list[dict], total: int, sr: int, max_seconds: float = 45.0) -> list[list[int]]:
    """Cut the narration into pieces of up to ~45 s at beat boundaries (inside the pauses),
    so the converter never sees a huge file and nothing is cut mid-word."""
    cuts = [0]
    last = 0.0
    for i in range(1, len(beats)):
        boundary = (beats[i - 1]["end"] + beats[i]["start"]) / 2
        if boundary - last >= max_seconds:
            cuts.append(int(boundary * sr))
            last = boundary
    cuts.append(total)
    return [[a, b] for a, b in zip(cuts, cuts[1:]) if b > a]


def _api():
    username = env("KAGGLE_USERNAME")
    if not (username and env("KAGGLE_API_TOKEN")):
        raise CloneError("Kaggle isn't connected (KAGGLE_USERNAME and KAGGLE_API_TOKEN GitHub secrets).")
    from kaggle.api.kaggle_api_extended import KaggleApi
    api = KaggleApi()
    api.authenticate()
    return api, username


def _slug(slug: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", slug.lower())[:36].strip("-")


def _push_kaggle(name: str, files: dict[str, Path], code: str) -> str:
    """Upload files as a private dataset `name`, wait until Kaggle has processed it, then push a GPU
    notebook of the same name that reads it. Returns the notebook id."""
    api, user = _api()
    ds_id = f"{user}/{name}"
    with tempfile.TemporaryDirectory() as d:
        d = Path(d)
        for fname, src in files.items():
            shutil.copy(src, d / fname)
        (d / "dataset-metadata.json").write_text(json.dumps(
            {"title": name.replace("-", " ")[:50], "id": ds_id, "licenses": [{"name": "other"}]}))
        try:
            resp = api.dataset_create_version(str(d), "new input", quiet=True, convert_to_csv=False,
                                              delete_old_versions=True)
            if getattr(resp, "error", None):
                raise RuntimeError(resp.error)
        except Exception as first:
            print(f"  no earlier upload to update ({first}); creating the dataset")
            try:
                resp = api.dataset_create_new(str(d), public=False, quiet=True, convert_to_csv=False)
            except ValueError as e:  # Kaggle sometimes answers a successful create with an empty body
                print(f"  create answered oddly ({e}); checking whether it went through")
                resp = None
            if getattr(resp, "error", None):
                raise CloneError(f"Kaggle refused the audio upload: {resp.error}")
    for _ in range(40):  # Kaggle processes uploads before notebooks can read them
        try:
            status = str(api.dataset_status(ds_id)).lower()
        except Exception as e:  # a brand-new dataset can 404 for a moment
            status = f"pending ({e})"
        if "ready" in status:
            break
        if "error" in status:
            raise CloneError(f"Kaggle couldn't process the audio upload ({status}).")
        time.sleep(15)
    else:
        raise CloneError(f"Kaggle didn't finish processing the audio upload in 10 minutes ({status}).")
    kernel_id = f"{user}/{name}"
    with tempfile.TemporaryDirectory() as d:
        d = Path(d)
        (d / "job.py").write_text(code, encoding="utf-8")
        meta = {"id": kernel_id, "title": name, "code_file": "job.py", "language": "python",
                "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
                "machine_shape": load_config()["illustrate"].get("accelerator", "NvidiaTeslaT4"),
                "dataset_sources": [ds_id], "competition_sources": [], "kernel_sources": [], "model_sources": []}
        (d / "kernel-metadata.json").write_text(json.dumps(meta))
        try:
            api.kernels_push(str(d))
        except Exception as e:
            if "409" in str(e):
                # Kaggle won't take a new version while an earlier one (e.g. from a stopped worker) is
                # still queued or running: push under a fresh name instead of waiting for it.
                kernel_id = f"{user}/{name}-{datetime.now(timezone.utc):%m%d%H%M%S}"
                print(f"  {name} is busy on Kaggle; pushing as {kernel_id}")
                meta.update(id=kernel_id, title=kernel_id.split("/")[1])
            else:
                print(f"  push with accelerator failed ({e}); retrying with the default GPU")
                meta.pop("machine_shape")
            (d / "kernel-metadata.json").write_text(json.dumps(meta))
            api.kernels_push(str(d))
    return kernel_id


def push(slug: str, raw_wav: Path, ref_wav: Path, job: dict) -> str:
    return _push_kaggle(f"docu-voice-{_slug(slug)}", {"raw.wav": raw_wav, "ref.wav": ref_wav},
                        KERNEL.replace("__JOB__", json.dumps(job)))


