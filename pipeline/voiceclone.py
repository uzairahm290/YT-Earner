def _read_wav(path: Path):
    import numpy as np
    with wave.open(str(path), "rb") as w:
        sr, n, width, ch = w.getframerate(), w.getnframes(), w.getsampwidth(), w.getnchannels()
        data = w.readframes(n)
    if width == 2:
        x = np.frombuffer(data, dtype="<i2").astype(np.float32) / 32768
    else:  # soundfile writes float WAVs by default; read anything else through ffmpeg
        raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(voice.SAMPLE_RATE),
                              "-f", "f32le", "-"], capture_output=True, check=True).stdout
        return np.frombuffer(raw, dtype=np.float32)
    if ch > 1:
        x = x.reshape(-1, ch).mean(1)
    return x


def _write_wav(path: Path, x) -> Path:
    import numpy as np
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(voice.SAMPLE_RATE)
        w.writeframes((np.clip(x, -1, 1) * 32767).astype("<i2").tobytes())
    return path


def _finish(slug: str, converted, timings: dict, started: float) -> dict:
    """Master the converted narration and store it exactly like voice.run does."""
    ep = Episode.load(slug)
    script = ep.read("script.json")
    mp3 = voice.master_to_mp3(converted)
    ep.write("voice/narration.mp3.b64", base64.b64encode(mp3).decode())
    ep.write("voice/timings.json", {**timings, "voice": VOICE_ID, "script_hash": voice.script_hash(script)})
    ep.write("voice/pending.json", "")
    meta = ep.read("meta.json")
    meta["voice"] = {"state": "done", "voice": VOICE_ID, "base_voice": cfg()["base_voice"],
                     "finished_at": datetime.now(timezone.utc).isoformat(),
                     "seconds_taken": round(time.time() - started),
                     "duration": timings["duration"], "size_kb": len(mp3) // 1024}
    ep.write("meta.json", meta)
    ep.set_status("voiced")
    print(f"  ✓ narration in your voice: {timings['duration'] / 60:.1f} min")
    return meta["voice"]


def run(slug: str) -> dict:
    ep = Episode.load(slug)
    script = ep.read("script.json")
    if not script:
        raise CloneError("There's no script to narrate yet.")
    started = time.time()
    meta = ep.read("meta.json")
    base = cfg()["base_voice"]
    print(f"[voice] {meta['topic']}: Kokoro ({base}) → your voice")
    track, beats = voice.narrate(script, base)
    timings = {"duration": round(len(track) / voice.SAMPLE_RATE, 2), "beats": beats}
    with tempfile.TemporaryDirectory() as d:
        d = Path(d)
        if os.getenv("DOCU_MOCK_VOICECLONE") == "1":
            return _finish(slug, track, timings, started)
        ref = reference_wav(d)
        raw = _write_wav(d / "raw.wav", track)
        job = {"chunks": chunks(beats, len(track), voice.SAMPLE_RATE), "tau": cfg()["tau"]}
        kernel_id = push(slug, raw, ref, job)
    ep.write("voice/pending.json", {**timings, "kernel": kernel_id})
    meta = ep.read("meta.json")
    meta["voice"] = {**(meta.get("voice") or {}), "kernel": kernel_id, "kaggle_status": "queued",
                     "pushed_at": datetime.now(timezone.utc).isoformat()}
    ep.write("meta.json", meta)
    from .illustrate import wait

    def note(s):
        m = ep.read("meta.json")
        m["voice"]["kaggle_status"] = s
        ep.write("meta.json", m)
    state, failure = wait(kernel_id, KAGGLE_WAIT, on_status=note)
    if state in ("complete", "error"):
        return _collect_and_finish(slug, kernel_id, started)
    meta = ep.read("meta.json")
    meta["voice"].update(state="waiting", kaggle_status=state)
    ep.write("meta.json", meta)
    print(f"  Kaggle still {state}; a later worker run collects the narration")
    return meta["voice"]


def _collect_and_finish(slug: str, kernel_id: str, started: float) -> dict:
    ep = Episode.load(slug)
    timings = ep.read("voice/pending.json")
    if not timings:
        raise CloneError("Lost track of this narration's timings. Record it again.")
    timings = {k: v for k, v in timings.items() if k != "kernel"}
    with tempfile.TemporaryDirectory() as d:
        wav = collect(kernel_id, Path(d))
        converted = _read_wav(wav)
    return _finish(slug, converted, timings, started)


def waiting() -> list[str]:
    return [slug for slug, f in Episode.read_many(["meta.json"]).items()
            if ((f.get("meta.json") or {}).get("voice") or {}).get("state") == "waiting"]


def collect_waiting(max_wait: float = 15 * 60) -> tuple[int, int]:
    from .illustrate import wait
    done = failed = 0
    for slug in waiting():
        ep = Episode(slug)
        job = (ep.read("meta.json") or {}).get("voice") or {}
        kernel_id = job.get("kernel")
        pushed = datetime.fromisoformat(job["pushed_at"]) if job.get("pushed_at") else datetime.now(timezone.utc)
        age_h = (datetime.now(timezone.utc) - pushed).total_seconds() / 3600
        print(f"[voice] checking on {kernel_id} ({age_h:.1f} h since it was sent)")
        try:
            state, _ = wait(kernel_id, max_wait)
            if state in ("complete", "error"):
                _collect_and_finish(slug, kernel_id, time.time())
                done += 1
            elif age_h > 6:
                raise CloneError("Kaggle never got to it (6 hours in its queue). Try again later.")
        except Exception as e:
            m = ep.read("meta.json")
            m.setdefault("voice", {}).update(state="error", error=str(e)[:500])
            ep.write("meta.json", m)
            failed += 1
    return done, failed
