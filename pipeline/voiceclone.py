def collect(kernel_id: str, out_dir: Path) -> Path:
    api, _ = _api()
    try:
        api.kernels_output(kernel_id, str(out_dir))
    except Exception as e:
        print(f"  couldn't download notebook output: {e}")
    result = json.loads((out_dir / "result.json").read_text()) if (out_dir / "result.json").exists() else {}
    wav = out_dir / "converted.wav"
