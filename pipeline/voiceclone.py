SETTINGS = "_settings"
VOICE_ID = "clone:me"
KAGGLE_WAIT = 40 * 60


class CloneError(RuntimeError):
    pass


def cfg() -> dict:
    return load_config()["voiceclone"]


# ──────────────────────────── the reference recording ────────────────────────────

def reference_info() -> dict | None:
    raw = get_store().read(SETTINGS, "voiceref/meta.json")
    return json.loads(raw) if raw else None


def save_reference(data: bytes, mime: str, name: str) -> dict:
    if len(data) > 20 * 1024 * 1024:
        raise CloneError("That recording is over 20 MB. 30-60 seconds is plenty.")
    if len(data) < 30_000:
        raise CloneError("That recording is too short. Upload 30-60 seconds of you talking.")
    store = get_store()
    store.write(SETTINGS, "voiceref/audio.b64", f"{mime};" + base64.b64encode(data).decode())
    meta = {"name": name.strip()[:40] or "My voice", "bytes": len(data), "mime": mime,
            "consent": True, "updated_at": datetime.now(timezone.utc).isoformat()}
    store.write(SETTINGS, "voiceref/meta.json", json.dumps(meta))
    return meta


def remove_reference() -> None:
    for name in ("voiceref/audio.b64", "voiceref/meta.json"):
        get_store().write(SETTINGS, name, "")


def reference_wav(folder: Path) -> Path:
    """The reference as clean mono WAV, trimmed to 60 s (worker side; needs ffmpeg)."""
    raw = get_store().read(SETTINGS, "voiceref/audio.b64")
    if not raw:
        raise CloneError("Upload a sample of your voice first (voice picker → Set up your voice).")
    _, _, b64 = raw.partition(";")
    src = folder / "ref.src"
    src.write_bytes(base64.b64decode(b64))
    out = folder / "ref.wav"
    r = subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(src), "-t", "60", "-ac", "1", "-ar", "22050",
                        "-af", "highpass=f=70,afftdn=nr=12,loudnorm=I=-20", str(out)], capture_output=True, text=True)
    if r.returncode != 0:
        raise CloneError(f"Couldn't read the voice sample: {r.stderr.strip()[-200:]}")
    return out


# ──────────────────────────── the Kaggle notebook ────────────────────────────

KERNEL = r'''
# Generated by docu-pipeline: converts a Kokoro narration to the creator's own voice (OpenVoice V2).
import glob, json, os, subprocess, sys, time, traceback
OUT = "/kaggle/working"
started = time.time()

def save(error=None, extra=None):
    json.dump({"error": error, "seconds": round(time.time() - started), **(extra or {})},
              open(os.path.join(OUT, "result.json"), "w"))

try:
    import torch
    if not torch.cuda.is_available():
        raise RuntimeError("No GPU on this session. Kaggle GPU needs a phone-verified account and weekly quota left.")
    torch.zeros(1, device="cuda").add_(1)
    pip = [sys.executable, "-m", "pip", "install", "-q"]
    subprocess.run(pip + ["--no-deps", "git+https://github.com/myshell-ai/OpenVoice.git"], check=True)
    # openvoice.text imports its English and Chinese text helpers at load time, even for voice conversion
    subprocess.run(pip + ["librosa", "soundfile", "unidecode", "inflect", "eng_to_ipa", "pypinyin", "jieba", "cn2an",
                          "huggingface_hub"], check=True)
    import librosa, numpy as np, soundfile
    from huggingface_hub import hf_hub_download
    from openvoice.api import OpenVoiceBaseClass, ToneColorConverter

    class Converter(ToneColorConverter):
        """ToneColorConverter without the audio watermark (its off switch crashes the base class)."""
        def __init__(self, config_path, device):
            OpenVoiceBaseClass.__init__(self, config_path, device)
            self.watermark_model = None
            self.version = getattr(self.hps, "_version_", "v1")

    config = hf_hub_download("myshell-ai/OpenVoiceV2", "converter/config.json")
    ckpt = hf_hub_download("myshell-ai/OpenVoiceV2", "converter/checkpoint.pth")
    tc = Converter(config, "cuda:0")
    tc.load_ckpt(ckpt)

    JOB = json.loads(r"""__JOB__""")
    raw = glob.glob("/kaggle/input/**/raw.wav", recursive=True)[0]
    ref = glob.glob("/kaggle/input/**/ref.wav", recursive=True)[0]
    tgt_se = tc.extract_se([ref])
    src_se = tc.extract_se([raw])
    audio, sr = soundfile.read(raw, dtype="float32")
    out = np.zeros_like(audio)
    tmp = "/kaggle/temp_chunk.wav"
    for k, (a, b) in enumerate(JOB["chunks"]):
        soundfile.write(tmp, audio[a:b], sr)
        conv = tc.convert(tmp, src_se, tgt_se, tau=JOB["tau"])
        conv = librosa.resample(conv, orig_sr=tc.hps.data.sampling_rate, target_sr=sr)
        n = b - a  # keep every chunk exactly as long as it was, so the beat timings still hold
        conv = conv[:n] if len(conv) >= n else np.pad(conv, (0, n - len(conv)))
        out[a:b] = conv
        print(f"chunk {k + 1}/{len(JOB['chunks'])} ({time.time() - started:.0f}s)", flush=True)
    soundfile.write(os.path.join(OUT, "converted.wav"), out, sr)
    save(extra={"chunks": len(JOB["chunks"])})
except Exception as e:
    traceback.print_exc()
    save(f"{e.__class__.__name__}: {e}"[:400])
'''


def chunks(beats: list[dict], total: int, sr: int, max_seconds: float = 45.0) -> list[list[int]]:
    """Cut the narration into pieces of up to ~45 s at beat boundaries (inside the pauses),
    so the converter never sees a huge file and nothing is cut mid-word."""
    cuts = [0]
    last = 0.0
    for i in range(1, len(beats)):
        boundary = (beats[i - 1]["end"] + beats[i]["start"]) / 2
        if boundary - last >= max_seconds:
            cuts.append(int(boundary * sr))
            last = boundary
    cuts.append(total)
    return [[a, b] for a, b in zip(cuts, cuts[1:]) if b > a]


def _api():
    username = env("KAGGLE_USERNAME")
    if not (username and env("KAGGLE_API_TOKEN")):
        raise CloneError("Kaggle isn't connected (KAGGLE_USERNAME and KAGGLE_API_TOKEN GitHub secrets).")
    from kaggle.api.kaggle_api_extended import KaggleApi
    api = KaggleApi()
    api.authenticate()
    return api, username


def _slug(slug: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", slug.lower())[:36].strip("-")


def push(slug: str, raw_wav: Path, ref_wav: Path, job: dict) -> str:
    """Upload the audio as a private dataset, then push the GPU notebook that reads it."""
    api, user = _api()
    ds_id = f"{user}/docu-voice-{_slug(slug)}"
    with tempfile.TemporaryDirectory() as d:
        d = Path(d)
        shutil.copy(raw_wav, d / "raw.wav")
        shutil.copy(ref_wav, d / "ref.wav")
        (d / "dataset-metadata.json").write_text(json.dumps(
            {"title": f"docu voice {_slug(slug)}"[:50], "id": ds_id, "licenses": [{"name": "other"}]}))
        try:
            api.dataset_create_version(str(d), "new narration", quiet=True, convert_to_csv=False,
                                       delete_old_versions=True)
        except Exception:
            api.dataset_create_new(str(d), public=False, quiet=True, convert_to_csv=False)
    for _ in range(40):  # Kaggle processes uploads before notebooks can read them
        status = str(api.dataset_status(ds_id)).lower()
        if "ready" in status:
            break
        if "error" in status:
            raise CloneError(f"Kaggle couldn't process the audio upload ({status}).")
        time.sleep(15)
    kernel_id = f"{user}/docu-voice-{_slug(slug)}"
    with tempfile.TemporaryDirectory() as d:
        d = Path(d)
        (d / "voice.py").write_text(KERNEL.replace("__JOB__", json.dumps(job)), encoding="utf-8")
        meta = {"id": kernel_id, "title": f"docu-voice-{_slug(slug)}", "code_file": "voice.py", "language": "python",
                "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
                "machine_shape": load_config()["illustrate"].get("accelerator", "NvidiaTeslaT4"),
                "dataset_sources": [ds_id], "competition_sources": [], "kernel_sources": [], "model_sources": []}
        (d / "kernel-metadata.json").write_text(json.dumps(meta))
        try:
            api.kernels_push(str(d))
        except Exception as e:
            print(f"  push with accelerator failed ({e}); retrying with the default GPU")
            meta.pop("machine_shape")
            (d / "kernel-metadata.json").write_text(json.dumps(meta))
            api.kernels_push(str(d))
    return kernel_id


def status(kernel_id: str) -> tuple[str, str]:
    from . import illustrate
    return illustrate.status(kernel_id)


def collect(kernel_id: str, out_dir: Path) -> Path:
    api, _ = _api()
    try:
        api.kernels_output(kernel_id, str(out_dir))
    except Exception as e:
        print(f"  couldn't download notebook output: {e}")
    result = json.loads((out_dir / "result.json").read_text()) if (out_dir / "result.json").exists() else {}
    wav = out_dir / "converted.wav"
    if result.get("error") or not wav.exists():
        from .illustrate import _log_tail
        raise CloneError(f"The voice notebook failed: {result.get('error') or 'no audio came back'}"
                         f" | {_log_tail(out_dir)[-300:]} (full log at kaggle.com/code/{kernel_id})")
    return wav


# ──────────────────────────── the job ────────────────────────────

def _read_wav(path: Path):
    import numpy as np
    with wave.open(str(path), "rb") as w:
        sr, n, width, ch = w.getframerate(), w.getnframes(), w.getsampwidth(), w.getnchannels()
        data = w.readframes(n)
    if width == 2:
        x = np.frombuffer(data, dtype="<i2").astype(np.float32) / 32768
    else:  # soundfile writes float WAVs by default; read anything else through ffmpeg
        raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(voice.SAMPLE_RATE),
                              "-f", "f32le", "-"], capture_output=True, check=True).stdout
        return np.frombuffer(raw, dtype=np.float32)
    if ch > 1:
        x = x.reshape(-1, ch).mean(1)
    return x


def _write_wav(path: Path, x) -> Path:
    import numpy as np
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(voice.SAMPLE_RATE)
        w.writeframes((np.clip(x, -1, 1) * 32767).astype("<i2").tobytes())
    return path


def _finish(slug: str, converted, timings: dict, started: float) -> dict:
    """Master the converted narration and store it exactly like voice.run does."""
    ep = Episode.load(slug)
    script = ep.read("script.json")
    mp3 = voice.master_to_mp3(converted)
    ep.write("voice/narration.mp3.b64", base64.b64encode(mp3).decode())
    ep.write("voice/timings.json", {**timings, "voice": VOICE_ID, "script_hash": voice.script_hash(script)})
    ep.write("voice/pending.json", "")
    meta = ep.read("meta.json")
    meta["voice"] = {"state": "done", "voice": VOICE_ID, "base_voice": cfg()["base_voice"],
                     "finished_at": datetime.now(timezone.utc).isoformat(),
                     "seconds_taken": round(time.time() - started),
                     "duration": timings["duration"], "size_kb": len(mp3) // 1024}
    ep.write("meta.json", meta)
    ep.set_status("voiced")
    print(f"  ✓ narration in your voice: {timings['duration'] / 60:.1f} min")
    return meta["voice"]


def run(slug: str) -> dict:
    ep = Episode.load(slug)
    script = ep.read("script.json")
    if not script:
        raise CloneError("There's no script to narrate yet.")
    started = time.time()
    meta = ep.read("meta.json")
    base = cfg()["base_voice"]
    print(f"[voice] {meta['topic']}: Kokoro ({base}) → your voice")
    track, beats = voice.narrate(script, base)
    timings = {"duration": round(len(track) / voice.SAMPLE_RATE, 2), "beats": beats}
    with tempfile.TemporaryDirectory() as d:
        d = Path(d)
        if os.getenv("DOCU_MOCK_VOICECLONE") == "1":
            return _finish(slug, track, timings, started)
        ref = reference_wav(d)
        raw = _write_wav(d / "raw.wav", track)
        job = {"chunks": chunks(beats, len(track), voice.SAMPLE_RATE), "tau": cfg()["tau"]}
        kernel_id = push(slug, raw, ref, job)
    ep.write("voice/pending.json", {**timings, "kernel": kernel_id})
    meta = ep.read("meta.json")
    meta["voice"] = {**(meta.get("voice") or {}), "kernel": kernel_id, "kaggle_status": "queued",
                     "pushed_at": datetime.now(timezone.utc).isoformat()}
    ep.write("meta.json", meta)
    from .illustrate import wait

    def note(s):
        m = ep.read("meta.json")
        m["voice"]["kaggle_status"] = s
        ep.write("meta.json", m)
    state, failure = wait(kernel_id, KAGGLE_WAIT, on_status=note)
    if state in ("complete", "error"):
        return _collect_and_finish(slug, kernel_id, started)
    meta = ep.read("meta.json")
    meta["voice"].update(state="waiting", kaggle_status=state)
    ep.write("meta.json", meta)
    print(f"  Kaggle still {state}; a later worker run collects the narration")
    return meta["voice"]


def _collect_and_finish(slug: str, kernel_id: str, started: float) -> dict:
    ep = Episode.load(slug)
    timings = ep.read("voice/pending.json")
    if not timings:
        raise CloneError("Lost track of this narration's timings. Record it again.")
    timings = {k: v for k, v in timings.items() if k != "kernel"}
    with tempfile.TemporaryDirectory() as d:
        wav = collect(kernel_id, Path(d))
        converted = _read_wav(wav)
    return _finish(slug, converted, timings, started)


def waiting() -> list[str]:
    return [slug for slug, f in Episode.read_many(["meta.json"]).items()
            if ((f.get("meta.json") or {}).get("voice") or {}).get("state") == "waiting"]


def collect_waiting(max_wait: float = 15 * 60) -> tuple[int, int]:
    from .illustrate import wait
    done = failed = 0
    for slug in waiting():
        ep = Episode(slug)
        job = (ep.read("meta.json") or {}).get("voice") or {}
        kernel_id = job.get("kernel")
        pushed = datetime.fromisoformat(job["pushed_at"]) if job.get("pushed_at") else datetime.now(timezone.utc)
        age_h = (datetime.now(timezone.utc) - pushed).total_seconds() / 3600
        print(f"[voice] checking on {kernel_id} ({age_h:.1f} h since it was sent)")
        try:
            state, _ = wait(kernel_id, max_wait)
            if state in ("complete", "error"):
                _collect_and_finish(slug, kernel_id, time.time())
                done += 1
            elif age_h > 6:
                raise CloneError("Kaggle never got to it (6 hours in its queue). Try again later.")
        except Exception as e:
            m = ep.read("meta.json")
            m.setdefault("voice", {}).update(state="error", error=str(e)[:500])
            ep.write("meta.json", m)
            failed += 1
    return done, failed
