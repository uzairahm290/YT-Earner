"""Your voice, American accent: Kokoro reads the script, OpenVoice V2 swaps the voice for yours.

How it works:
  1. Once: you upload 30-60 s of yourself speaking (the reference), and confirm it's your voice.
  2. Per video, on the GitHub worker: Kokoro narrates the script in an American voice, exactly as
     for the normal narration (same beats, same timings).
  3. That raw narration and your reference go to Kaggle as a private dataset; a GPU notebook runs
     OpenVoice V2's tone-color converter (MIT licence, fine for monetized videos): words, pacing and
     the American accent stay, the voice timbre becomes yours.
  4. The worker collects the result, masters it like any narration, and stores it with the same beat
     timings, so captions and editing don't change.

Kaggle's GPU queue can be slow, so like the illustrations a job waits 40 minutes, then hands over to
a later worker run (meta.voice.state = "waiting").

Set DOCU_MOCK_VOICECLONE=1 to skip Kaggle (tests, demo): the Kokoro audio is passed through.
"""
