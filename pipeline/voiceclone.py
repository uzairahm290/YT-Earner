# ──────────────────────────── the reference recording ────────────────────────────

def reference_info() -> dict | None:
    raw = get_store().read(SETTINGS, "voiceref/meta.json")
    return json.loads(raw) if raw else None


def save_reference(data: bytes, mime: str, name: str) -> dict:
    if len(data) > 20 * 1024 * 1024:
        raise CloneError("That recording is over 20 MB. 30-60 seconds is plenty.")
    if len(data) < 30_000:
        raise CloneError("That recording is too short. Upload 30-60 seconds of you talking.")
    store = get_store()
    store.write(SETTINGS, "voiceref/audio.b64", f"{mime};" + base64.b64encode(data).decode())
    store.write(SETTINGS, "voiceref/clean.b64", "")  # the old cleaned copy belongs to the old sample
    meta = {"name": name.strip()[:40] or "My voice", "bytes": len(data), "mime": mime,
            "consent": True, "updated_at": datetime.now(timezone.utc).isoformat(),
            "clean": {"state": "queued", "requested_at": datetime.now(timezone.utc).isoformat()}}
    store.write(SETTINGS, "voiceref/meta.json", json.dumps(meta))
    return meta


def remove_reference() -> None:
    for name in ("voiceref/audio.b64", "voiceref/meta.json", "voiceref/clean.b64"):
        get_store().write(SETTINGS, name, "")


def reference_wav(folder: Path, prefer_clean: bool = True, sample_rate: int = 22050, light: bool = False) -> Path:
    """The voice sample as mono WAV (worker side; needs ffmpeg). The cleaned version when there is
    one; otherwise the upload with a light cleanup, trimmed to 60 s (cleanup input keeps 3 minutes)."""
    store = get_store()
    raw = (store.read(SETTINGS, "voiceref/clean.b64") if prefer_clean else None) or \
        store.read(SETTINGS, "voiceref/audio.b64")
    if not raw:
        raise CloneError("Upload a sample of your voice first (voice picker → Set up your voice).")
    _, _, b64 = raw.partition(";")
    src = folder / "ref.src"
    src.write_bytes(base64.b64decode(b64))
    out = folder / "ref.wav"
    af = "highpass=f=60" if light else "highpass=f=70,afftdn=nr=12,loudnorm=I=-20"
    r = subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(src), "-t", "180" if light else "60", "-ac", "1",
                        "-ar", str(sample_rate), "-af", af, str(out)], capture_output=True, text=True)
    if r.returncode != 0:
        raise CloneError(f"Couldn't read the voice sample: {r.stderr.strip()[-200:]}")
    return out


